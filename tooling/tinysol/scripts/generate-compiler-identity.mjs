import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak_256 } from "@noble/hashes/sha3";

const here = dirname(fileURLToPath(import.meta.url));
const workspace = resolve(here, "..");
const check = process.argv.includes("--check");
const compilerFiles = [
  "src/compiler-artifacts.ts", "src/compiler-types.ts", "src/codegen.ts", "src/lexer.ts", "src/parser.ts", "src/semantic.ts",
  "src/abi.ts", "src/assembler.ts", "src/bytes.ts", "src/errors.ts", "src/isa.ts", "src/package.ts", "src/validator.ts", "package.json"
].sort();

const chunks = [];
for (const file of compilerFiles) {
  chunks.push(new TextEncoder().encode(`${file}\0`));
  chunks.push(new Uint8Array(await readFile(resolve(workspace, file))));
  chunks.push(Uint8Array.of(0));
}
const isaSource = await readFile(resolve(workspace, "src/generated-isa.ts"));
chunks.push(new TextEncoder().encode("src/generated-isa.ts\0"), new Uint8Array(isaSource));
const size = chunks.reduce((sum, item) => sum + item.length, 0);
const combined = new Uint8Array(size); let offset = 0;
for (const item of chunks) { combined.set(item, offset); offset += item.length; }
const fingerprint = `0x${Buffer.from(keccak_256(combined)).toString("hex")}`;
const lock = await readFile(resolve(workspace, "package-lock.json"));
const lockHash = createHash("sha256").update(lock).digest("hex");
const output = `// Generated by scripts/generate-compiler-identity.mjs. Do not edit manually.\nexport const COMPILER_SOURCE_FINGERPRINT = "${fingerprint}" as const;\nexport const COMPILER_DEPENDENCY_LOCK_SHA256 = "${lockHash}" as const;\n`;
const outputPath = resolve(workspace, "src/generated-compiler-identity.ts");
if (check) {
  const current = await readFile(outputPath, "utf8");
  if (current !== output) throw new Error("COMPILER_IDENTITY_DRIFT");
} else await writeFile(outputPath, output);
