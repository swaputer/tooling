import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { keccak_256 } from "@noble/hashes/sha3";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const repositoryRoot = resolve(packageRoot, "../..");
const kernelSource = await readFile(resolve(repositoryRoot, "src/SwapVMKernel.sol"), "utf8");
const miniVmSource = await readFile(resolve(repositoryRoot, "src/SwapVMMiniVM.sol"), "utf8");
const frozenSpec = await readFile(resolve(repositoryRoot, "docs/spec/SwapVM-v1.1-frozen-spec.md"), "utf8");

function capture(source, expression, label) {
  const match = source.match(expression);
  if (match?.[1] === undefined) throw new Error(`unable to extract ${label}`);
  return match[1].replaceAll("_", "");
}

function topic(signature) {
  return `0x${Buffer.from(keccak_256(new TextEncoder().encode(signature))).toString("hex")}`;
}

function wordWidth(signature) {
  const parameters = signature.match(/\((.*)\)$/)?.[1];
  if (parameters === undefined) throw new Error(`unable to derive data width from ${signature}`);
  return (parameters === "" ? 0 : parameters.split(",").length) * 32;
}

const receiptVersion = capture(kernelSource, /RECEIPT_VERSION\s*=\s*(\d+)/, "RECEIPT_VERSION");
const kernelEmitter = capture(kernelSource, /KERNEL_EMITTER_ID\s*=\s*(0x[0-9a-fA-F]{64})/, "KERNEL_EMITTER_ID");
const worldSignature = capture(
  kernelSource,
  /WORLD_EXECUTION_SELECTOR\s*=\s*\n?\s*keccak256\("([^"]+)"\)/,
  "WORLD_EXECUTION_SELECTOR signature"
);
const deploymentSignature = capture(
  kernelSource,
  /MINI_CONTRACT_DEPLOYED_SELECTOR\s*=\s*\n?\s*keccak256\("([^"]+)"\)/,
  "MINI_CONTRACT_DEPLOYED_SELECTOR signature"
);
const maxRecords = capture(miniVmSource, /MAX_RECEIPT_RECORDS\s*=\s*([\d_]+)/, "MAX_RECEIPT_RECORDS");
const maxData = capture(miniVmSource, /MAX_RECORD_DATA_BYTES\s*=\s*([\d_]+)/, "MAX_RECORD_DATA_BYTES");
const maxPayload = capture(
  miniVmSource,
  /MAX_RECEIPT_PAYLOAD_BYTES\s*=\s*([\d_]+)/,
  "MAX_RECEIPT_PAYLOAD_BYTES"
);
const specVersion = capture(frozenSpec, /version\s+uint8\s+=\s+(\d+)/, "v1 spec version");
const specFlags = capture(frozenSpec, /flags\s+uint8\s+=\s+(\d+)\s+in v1/, "v1 spec flags");
const specMaxTopics = capture(frozenSpec, /maximum\s+([\d,]+)\s+mini topics per record/, "v1 max topics").replaceAll(
  ",",
  ""
);
const specMaxData = capture(frozenSpec, /maximum\s+([\d,]+)\s+data bytes per record/, "v1 max data").replaceAll(
  ",",
  ""
);
const specMaxRecords = capture(frozenSpec, /maximum\s+([\d,]+)\s+records per VM execution/, "v1 max records").replaceAll(
  ",",
  ""
);
const specMaxPayload = capture(frozenSpec, /maximum\s+([\d,]+)\s+encoded `payload` bytes/, "v1 max payload").replaceAll(
  ",",
  ""
);
for (const [solidityValue, specValue, label] of [
  [receiptVersion, specVersion, "receipt version"],
  [maxRecords, specMaxRecords, "record limit"],
  [maxData, specMaxData, "data limit"],
  [maxPayload, specMaxPayload, "payload limit"]
]) {
  if (solidityValue !== specValue) throw new Error(`${label} differs between Solidity and the frozen v1.1 spec`);
}
const worldDataBytes = wordWidth(worldSignature);
const deploymentDataBytes = wordWidth(deploymentSignature);

const generated = `// Generated by scripts/generate-constants.mjs from src/SwapVMKernel.sol,
// src/SwapVMMiniVM.sol and the frozen v1.1 section 23. Do not edit by hand;
// \`npm run generate:constants\` updates it.
export const RECEIPT_VERSION = ${receiptVersion} as const;
export const RECEIPT_FLAGS_V1 = ${specFlags} as const;
export const KERNEL_EMITTER_ID =
  "${kernelEmitter.toLowerCase()}" as const;
export const WORLD_EXECUTION_SIGNATURE =
  "${worldSignature}" as const;
export const WORLD_EXECUTION_TOPIC =
  "${topic(worldSignature)}" as const;
export const MINI_CONTRACT_DEPLOYED_SIGNATURE =
  "${deploymentSignature}" as const;
export const MINI_CONTRACT_DEPLOYED_TOPIC =
  "${topic(deploymentSignature)}" as const;
export const MAX_RECEIPT_RECORDS = ${maxRecords} as const;
export const MAX_RECORD_TOPICS = ${specMaxTopics} as const;
export const MAX_RECORD_DATA_BYTES = ${maxData} as const;
export const MAX_RECEIPT_PAYLOAD_BYTES = ${maxPayload} as const;
export const WORLD_EXECUTION_DATA_BYTES = ${worldDataBytes} as const;
export const MINI_CONTRACT_DEPLOYED_DATA_BYTES = ${deploymentDataBytes} as const;
`;

const destination = resolve(packageRoot, "src/constants.ts");
if (process.argv.includes("--check")) {
  const current = await readFile(destination, "utf8");
  if (current !== generated) {
    throw new Error("src/constants.ts does not match the Solidity receipt constants; run npm run generate:constants");
  }
} else {
  await writeFile(destination, generated);
}
